function crackTime(seconds: number): string {
  const years = yearsFromSeconds(seconds);
  if (years > 1e12) return 'más que la edad del universo para adivinarla';
  const scales: [number, string][] = [
    [31536000e9, 'miles de millones de años'],
    [31536000e6, 'millones de años'],
    [31536000e3, 'miles de años'],
    [31536000, 'años'],
    [86400, 'días'],
    [3600, 'horas'],
    [60, 'minutos'],
  ];
  for (const [value, name] of scales) {
    if (seconds >= value) return `unos ${Math.round(seconds / value).toLocaleString('es-AR')} ${name} para adivinarla`;
  }
  return 'menos de un minuto para adivinarla';
}

